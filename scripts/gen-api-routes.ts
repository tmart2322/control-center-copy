/**
 * Generates app/api/v1/**\/route.ts from the route table (src/contract/routes.ts).
 * Every handler is a thin `handle('<routeKey>')` wrapper. Run: `npm run gen:routes`.
 * Re-run after adding a route to the contract; the orchestrator owns the contract.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { routes, type RouteKey } from '../src/contract/routes';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const byPath = new Map<string, Array<{ method: string; key: RouteKey }>>();
for (const key of Object.keys(routes) as RouteKey[]) {
  const def = routes[key];
  const list = byPath.get(def.path) ?? [];
  if (list.some((x) => x.method === def.method)) throw new Error(`duplicate ${def.method} ${def.path}`);
  list.push({ method: def.method, key });
  byPath.set(def.path, list);
}

let n = 0;
for (const [p, handlers] of [...byPath].sort(([a], [b]) => a.localeCompare(b))) {
  const dir = path.join(root, 'app/api/v1', ...p.split('/').filter(Boolean).map((seg) => (seg.startsWith(':') ? `[${seg.slice(1)}]` : seg)));
  mkdirSync(dir, { recursive: true });
  const lines = [
    '// Generated by scripts/gen-api-routes.ts from src/contract/routes.ts. Do not edit by hand.',
    "import { handle } from '@/server/http';",
    '',
    "export const runtime = 'nodejs';",
    "export const dynamic = 'force-dynamic';",
    '',
    ...handlers.sort((a, b) => a.method.localeCompare(b.method)).map((h) => `export const ${h.method} = handle('${h.key}');`),
    '',
  ];
  writeFileSync(path.join(dir, 'route.ts'), lines.join('\n'));
  n++;
}
console.log(`wrote ${n} route files for ${Object.keys(routes).length} routes`);
